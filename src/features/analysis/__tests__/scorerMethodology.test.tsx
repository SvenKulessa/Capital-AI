import test from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { calculateMethodology, methodologyBand, METHODOLOGY_EXAMPLE, METHODOLOGY_FACTORS } from '../scorerMethodology';
import { ScorerMethodologyDemo } from '../ScorerMethodologyDemo';
import { HistoricalAnalyticsDemo } from '../HistoricalAnalyticsDemo';
const close = (actual: number, expected: number) => assert.ok(Math.abs(actual - expected) < 1e-9);
test('historical ten-factor arithmetic, inversion and missing input semantics', () => {
  const full = calculateMethodology(METHODOLOGY_EXAMPLE);
  close(full.score!, 74.08);
  close(full.weightCoverage, 1);
  close(full.factors.find(f => f.id === 'exchange_liquidity')!.contribution!, 2.96);
  close(full.factors.find(f => f.id === 'data_quality_risk')!.contribution!, 3.60);
  assert.equal(full.complete, true);
  assert.equal(full.scoreEligible, false);
  assert.equal(full.rankEligible, false);
  assert.equal(full.decisionEligible, false);
  const partial = calculateMethodology({ trend: 80, momentum: 60 });
  close(partial.score!, 71.11111111111111);
  close(partial.weightCoverage, .36);
  assert.equal(partial.complete, false);
  assert.equal(partial.availableCount, 2);
  assert.equal(calculateMethodology({ data_quality_risk: 10 }).score, 90);
  assert.equal(calculateMethodology({}).score, null);
  assert.equal(calculateMethodology({ trend: null }).score, null);
  assert.equal(calculateMethodology({ trend: 0 }).score, 0);
  for (const input of [NaN, Infinity, -1, 101]) assert.throws(() => calculateMethodology({ trend: input }));
  assert.throws(() => calculateMethodology({ unknown: 10 } as any));
});
test('one versioned set of thresholds with exact boundary handling', () => {
  for (const [value, label] of [[90,'90–100'],[89.999,'80 bis unter 90'],[80,'80 bis unter 90'],[79.999,'70 bis unter 80'],[70,'70 bis unter 80'],[69.999,'60 bis unter 70'],[60,'60 bis unter 70'],[59.999,'Unter 60']] as const) assert.ok(methodologyBand(value).startsWith(label));
  for (const value of [null, NaN, Infinity, -1, 101]) assert.equal(methodologyBand(value), 'Nicht verfügbar');
});
test('accessible educational profile and existing Learning offer without checkout mutation', () => {
  const html = renderToStaticMarkup(<ScorerMethodologyDemo />);
  for (const factor of METHODOLOGY_FACTORS) assert.ok(html.includes(factor.label));
  assert.match(html, /74,08/);
  assert.match(html, /keine Live-Bewertung/);
  assert.match(html, /kein ausgewähltes Asset/);
  assert.match(html, /Kalibrierte Modellkonfidenz/);
  assert.match(html, /aria-live="polite"/);
  assert.match(html, /<label[^>]+for=/);
  assert.match(html, /\/learning\?tab=glossar#learning-offer/);
  assert.doesNotMatch(html, /checkout\.stripe\.com|BUY|SELL|A_setup/);
  assert.equal((html.match(/<meter /g) ?? []).length, 10);
  assert.ok(renderToStaticMarkup(<HistoricalAnalyticsDemo />).includes('Methodik-Demo öffnen'));
  assert.ok(!renderToStaticMarkup(<HistoricalAnalyticsDemo showMethodology={false} />).includes('Methodik-Demo öffnen'));
});
