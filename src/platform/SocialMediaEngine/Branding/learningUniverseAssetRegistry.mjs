export function canPreviewLearningUniverseAsset(asset) {
  return Boolean(asset && knownAssets.get(asset.id) === asset &&
    asset.cataloguePreview === 'OWNER_DIRECTED_FIRST_PARTY' &&
    asset.origin === 'GENERATED' && asset.publishApproval === false &&
    asset.thirdPartyRedistribution === 'NOT_PROVEN' && asset.mediaKitReview === 'REVIEW_REQUIRED' &&
    asset.publicUrl === '/branding/learning-universe/' + asset.tab + '.svg' &&
    /^[0-9a-f]{64}$/.test(asset.sha256));
}
export function catalogueLearningUniverseAssets() {
  return LEARNING_UNIVERSE_ASSETS.filter(canPreviewLearningUniverseAsset);
}
